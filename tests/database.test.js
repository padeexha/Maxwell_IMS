import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('database authorization, validation, atomic receiving and audit integrity', async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
 await db.exec(await readFile(new URL('../supabase/migrations/202610290001_inventory.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/migrations/202610300001_product_edit_delete.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/migrations/202610300002_auto_profile_trigger.sql',import.meta.url),'utf8'));
 const ids=['00000000-0000-0000-0000-000000000001','00000000-0000-0000-0000-000000000002','00000000-0000-0000-0000-000000000003','00000000-0000-0000-0000-000000000004'];
 for(let i=0;i<4;i++){
  await db.query('insert into auth.users (id, email) values ($1, $2)',[ids[i], `staff${i}@example.com`]);
  if(i<3)await db.query('update public.profiles set name=$2, role=$3 where id=$1',[ids[i],['Admin','Manager','Worker'][i],['Administrator','Manager','Worker'][i]]);
 }
 const as=async(i)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[ids[i]]);await db.exec('set role authenticated');};
 const call=(action,payload)=>db.query('select public.inventory_command($1,$2::jsonb) as result',[action,JSON.stringify(payload)]);
 const denied=async(action,payload)=>assert.rejects(()=>call(action,payload));
 await db.exec('set role anon');
 await assert.rejects(()=>db.query('select * from public.products'));
 await denied('create_product',{});
 await as(3);await denied('receive',{});assert.equal((await db.query('select * from public.products')).rows.length,0);
 await as(0);
 await call('create_product',{name:'Test TV',sku:'TV-1',category:'Electronics',reorderLevel:2,unitValue:1500});
 const product=(await db.query('select * from public.products')).rows[0];
 await call('update_product',{id:product.id,name:'Updated TV Name',sku:'TV-1',category:'Electronics',model:'Model-X',brand:'Sony',reorderLevel:3,unitValue:1600});
 const updatedProduct=(await db.query('select * from public.products where id=$1',[product.id])).rows[0];
 assert.equal(updatedProduct.name,'Updated TV Name');
 assert.equal(updatedProduct.model,'Model-X');
 await call('create_product',{name:'Deletable Item',sku:'DEL-1',category:'Other',reorderLevel:1,unitValue:50});
 const delProduct=(await db.query("select * from public.products where sku='DEL-1'")).rows[0];
 await denied('create_product',{name:'Duplicate',sku:'tv-1',category:'Electronics',reorderLevel:0,unitValue:0});
 await denied('set_value',{id:product.id,value:-1});
 await denied('set_value',{id:product.id,value:'NaN'});
 await denied('set_access',{id:ids[0],role:'Worker',active:false});
 await as(1);
 await denied('create_product',{name:'Forbidden'});await denied('set_value',{id:product.id,value:1});await denied('set_access',{id:ids[2],role:'Administrator',active:true});
 await denied('update_product',{id:product.id,name:'Hacked',sku:'TV-1',category:'Electronics',reorderLevel:1,unitValue:100});
 await denied('delete_product',{id:delProduct.id});
 await as(0);
 await call('delete_product',{id:delProduct.id});
 assert.equal((await db.query("select * from public.products where sku='DEL-1'")).rows.length,0);
 await call('receive',{productId:product.id,quantity:2,serials:['SN1','SN2']});
 await denied('delete_product',{id:product.id});
 await denied('receive',{productId:product.id,quantity:2,serials:['SN3','sn1']});
 assert.equal((await db.query('select * from public.units')).rows.length,2,'failed batch rolls back all units');
 assert.equal((await db.query("select * from public.activities where type='add'")).rows.length,2,'failed batch rolls back audit');
 for(const quantity of [0,101,1.5])await denied('receive',{productId:product.id,quantity,serials:[]});
 await as(2);
 assert.equal((await db.query('select * from public.profiles')).rows.length,1);
 assert.equal((await db.query('select * from public.activities')).rows.length,0);
 await denied('receive',{productId:product.id,quantity:1,serials:[]});
 await assert.rejects(()=>db.query("update public.profiles set role='Administrator'"));
 await assert.rejects(()=>db.query("update public.units set status='Sold'"));
 await assert.rejects(()=>db.query("insert into public.activities(type,text,actor,\"by\") values ('sale','Forged',$1,'Admin')",[ids[2]]));
 const unit=(await db.query('select * from public.units')).rows[0];
 await call('transition',{id:unit.id,status:'Sold',version:1});
 await denied('transition',{id:unit.id,status:'Sold',version:1});
 await denied('transition',{id:unit.id,status:'Repair',version:2});
 await call('transition',{id:unit.id,status:'Available',version:2});
 await call('transition',{id:unit.id,status:'Repair',version:3});
 await denied('transition',{id:unit.id,status:'Available',version:4});
 await as(1);await call('transition',{id:unit.id,status:'Available',version:4});
 const sale=(await db.query("select * from public.activities where type='sale'")).rows;
 assert.equal(sale.length,1);assert.equal(sale[0].actor,ids[2]);assert.equal(sale[0].by,'Worker');
 await as(0);await call('set_access',{id:ids[2],role:'Worker',active:false});
 await as(2);await denied('transition',{id:unit.id,status:'Sold',version:5});
 assert.equal((await db.query('select * from public.units')).rows.length,0);
 await db.close();
});
